def cmd_setup(args: argparse.Namespace) -> int:
    guard_privileged_user(args)
    if args.dry_run:
        print("dry-run: would create", TABLE_NAME)
        return 0
    import oracledb

    with connect(args, action="setup") as connection:
        with connection.cursor() as cursor:
            for ddl in DDL_STATEMENTS:
                try:
                    cursor.execute(ddl)
                except oracledb.DatabaseError as exc:
                    (error,) = exc.args
                    if error.code in (955, 1408):  # already exists / already indexed
                        continue
                    raise
    print(f"{TABLE_NAME} is ready in schema {oracle_user().upper()}.")
    return 0


def cmd_start(args: argparse.Namespace) -> int:
    guard_privileged_user(args)
    pid = running_pid()
    if pid:
        print(f"Already running (pid {pid}). Use 'status' or 'stop' first.")
        return 1

    if args.foreground:
        return run_load(args)

    RUNTIME_DIR.mkdir(parents=True, exist_ok=True)
    STATE_FILE.unlink(missing_ok=True)
    argv = sys.argv[1:]
    argv[argv.index("start")] = "_run"
    with open(LOG_FILE, "a") as log_handle:
        log_handle.write(f"\n===== start {utc_now()} =====\n")
        log_handle.flush()
        proc = subprocess.Popen(
            [sys.executable, str(Path(__file__).resolve()), *argv],
            stdout=log_handle,
            stderr=subprocess.STDOUT,
            stdin=subprocess.DEVNULL,
            start_new_session=True,  # survives the terminal closing
            cwd=str(PROJECT_ROOT),
            env=os.environ.copy(),
        )

    # Give it a moment to connect so config/credential errors surface now.
    for _ in range(40):
        time.sleep(0.25)
        state = read_json(STATE_FILE)
        if proc.poll() is not None:
            print("Simulator exited during startup. Last log lines:\n")
            print(tail(LOG_FILE))
            return 1
        if state and state.get("status") == "running":
            break

    print(f"Started ingest simulator (pid {proc.pid}), mode={args.mode}, commit_mode={args.commit_mode}.")
    print(f"  log:    {LOG_FILE}")
    print("  status: python scripts/ingest_simulator.py status")
    print("  stop:   python scripts/ingest_simulator.py stop")
    return 0


def cmd_status(args: argparse.Namespace) -> int:
    pid = running_pid()
    state = read_json(STATE_FILE)

    if args.json:
        print(json.dumps({"running": bool(pid), "state": state}, indent=2, default=str))
        return 0 if pid else 3

    if not pid and not state:
        print("Not running. No previous run recorded.")
        return 3

    if pid:
        print(f"RUNNING (pid {pid})")
    else:
        print(f"NOT RUNNING - last run: {state.get('status') if state else 'unknown'}")
        if PID_FILE.exists():
            PID_FILE.unlink(missing_ok=True)  # stale pid file

    if state:
        rows = [
            ("mode", f"{state['mode']} / commit per {state['commit_mode']}"),
            ("phase", state["phase"]),
            ("workers", f"{state['active_workers']} active of {state['max_workers']}"),
            ("throughput", f"{state['rows_per_sec']:,} rows/s, {state['commits_per_sec']:,} commits/s"),
            ("avg commit", f"{state['avg_commit_ms']} ms"),
            ("totals", f"{state['rows_total']:,} rows, {state['commits_total']:,} commits, "
                       f"{state['errors_total']} errors"),
            ("started", state["started_at"]),
            ("ends", state["ends_at"]),
            ("updated", state["updated_at"]),
        ]
        if state.get("last_error"):
            rows.append(("last error", state["last_error"]))
        if state.get("dry_run"):
            rows.append(("note", "DRY RUN - no database was touched"))
        width = max(len(k) for k, _ in rows)
        for key, value in rows:
            print(f"  {key.ljust(width)}  {value}")
    return 0 if pid else 3


def cmd_stop(args: argparse.Namespace) -> int:
    pid = running_pid()
    if not pid:
        print("Not running.")
        PID_FILE.unlink(missing_ok=True)
        return 0

    print(f"Stopping pid {pid} ...")
    os.kill(pid, signal.SIGTERM)
    deadline = time.monotonic() + args.timeout
    while time.monotonic() < deadline:
        if not is_our_process(pid):
            break
        time.sleep(0.5)
    else:
        print(f"Did not stop within {args.timeout}s; sending SIGKILL "
              "(Oracle will roll back any open transactions).")
        os.kill(pid, signal.SIGKILL)
        PID_FILE.unlink(missing_ok=True)

    state = read_json(STATE_FILE) or {}
    print(f"Stopped. rows={state.get('rows_total', 0):,} commits={state.get('commits_total', 0):,} "
          f"errors={state.get('errors_total', 0)}")
    return 0


def cmd_cleanup(args: argparse.Namespace) -> int:
    guard_privileged_user(args)
    if running_pid():
        print("Simulator is running. Stop it first.")
        return 1
    action = "DROP" if args.drop else "TRUNCATE"
    if not args.yes:
        answer = input(f"{action} table {TABLE_NAME} in schema {oracle_user().upper()}? Type YES: ")
        if answer.strip() != "YES":
            print("Cancelled.")
            return 1
    if args.dry_run:
        print(f"dry-run: would {action} {TABLE_NAME}")
        return 0
    sql = f"DROP TABLE {TABLE_NAME} PURGE" if args.drop else f"TRUNCATE TABLE {TABLE_NAME}"
    with connect(args, action="cleanup") as connection:
        with connection.cursor() as cursor:
            cursor.execute(sql)
    print(f"{action} {TABLE_NAME} done.")
    return 0


