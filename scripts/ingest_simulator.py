#!/usr/bin/env python3
"""Simulate a fast message-ingest workload (like a RabbitMQ consumer) against Oracle.

Runs in the background and is controlled with start / stop / status commands,
so the monitor dashboard can be watched while load comes and goes.

Commands
    setup     Create the INGEST_SIM_ORDERS table (idempotent).
    start     Launch the load generator in the background.
    status    Show whether it is running, its phase, and live throughput.
    stop      Stop it gracefully (in-flight work is committed or rolled back).
    cleanup   Truncate (or --drop) the demo table.

Load modes
    steady    Constant load, optionally capped with --rate rows/sec.
    burst     Full load for --burst-seconds, idle for --pause-seconds, repeat.
    ramp      Start with --start-workers, add --step-workers every
              --step-seconds up to --workers. Optionally stop automatically
              once average commit latency exceeds --stop-latency-ms.

Commit modes
    row       One INSERT + COMMIT per message. This matches the existing
              RabbitMQ consumer and produces high commits/sec and
              'log file sync' waits - the classic "ingest is crawling" shape.
    batch     executemany() of --batch-size rows, one COMMIT per batch.
              Fewer commits, much more redo per second.

Examples (run from the project root)
    uv run --env-file .env.mcp --env-file .env.loadgen \\
        python scripts/ingest_simulator.py setup

    uv run --env-file .env.mcp --env-file .env.loadgen \\
        python scripts/ingest_simulator.py start --mode steady --workers 4 --rate 60

    uv run python scripts/ingest_simulator.py status
    uv run python scripts/ingest_simulator.py stop

Background mode is for Linux/macOS (POSIX signals, detached sessions). On
Windows use `start --foreground` and stop it with Ctrl+C or --duration;
`status` is safe there, but `stop` terminates the process without a
graceful shutdown (Oracle rolls back its open transactions).
"""

