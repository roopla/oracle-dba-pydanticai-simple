def oracle_user() -> str:
    return os.environ.get("LOADGEN_ORACLE_USER") or os.environ.get("ORACLE_USER", "")


def guard_privileged_user(args: argparse.Namespace) -> None:
    if args.dry_run:
        return
    user = oracle_user().strip().upper()
    if user in PRIVILEGED_USERS and not args.allow_privileged_user:
        sys.exit(
            f"Refusing to run as {user}: the demo table would be created in the "
            f"{user} schema and could fill the SYSTEM tablespace.\n"
            "Create a dedicated user with scripts/ingest_simulator_user.sql and set "
            "LOADGEN_ORACLE_USER / LOADGEN_ORACLE_PASSWORD (e.g. in .env.loadgen).\n"
            "To override anyway, pass --allow-privileged-user."
        )


class _FakeCursor:
    """Dry-run cursor: simulates insert cost without a database."""

    def setinputsizes(self, *args: Any) -> None:
        pass

    def execute(self, sql: str, params: Any = None) -> None:
        time.sleep(0.0005)

    def executemany(self, sql: str, rows: list[Any]) -> None:
        time.sleep(0.0002 * len(rows))

    def close(self) -> None:
        pass


class _FakeConnection:
    module = action = client_identifier = ""

    def cursor(self) -> _FakeCursor:
        return _FakeCursor()

    def commit(self) -> None:
        time.sleep(0.001)

    def rollback(self) -> None:
        pass

    def close(self) -> None:
        pass


def connect(args: argparse.Namespace, action: str) -> Any:
    if args.dry_run:
        return _FakeConnection()

    import oracledb

    from oracle_core.config import get_settings
    from oracle_core.db import build_dsn

    settings = get_settings()
    user = os.environ.get("LOADGEN_ORACLE_USER") or settings.oracle_user
    password = (
        os.environ.get("LOADGEN_ORACLE_PASSWORD")
        or settings.oracle_password.get_secret_value()
    )
    database = args.database or settings.oracle_default_pdb_name
    connection = oracledb.connect(
        user=user,
        password=password,
        dsn=build_dsn(database),
        tcp_connect_timeout=10,
    )
    # Visible in V$SESSION.MODULE / ACTION so the agent and DBAs can spot it.
    connection.module = MODULE_NAME
    connection.action = action
    connection.client_identifier = f"ingest_sim:{os.getpid()}"
    return connection


