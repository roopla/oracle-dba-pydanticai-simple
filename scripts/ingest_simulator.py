def run_load(args: argparse.Namespace) -> int:
    RUNTIME_DIR.mkdir(parents=True, exist_ok=True)
    PID_FILE.write_text(str(os.getpid()))

    stop_event = threading.Event()
    stop_requested = threading.Event()

    def on_signal(signum: int, _frame: Any) -> None:
        log(f"received {signal.Signals(signum).name}, stopping")
        stop_requested.set()
        stop_event.set()

    signal.signal(signal.SIGTERM, on_signal)
    signal.signal(signal.SIGINT, on_signal)

    controller = Controller(args.workers)
    metrics = Metrics()
    started_wall = time.time()
    started = time.monotonic()
    deadline = started + args.duration if args.duration > 0 else None
    deadline_wall = started_wall + args.duration if args.duration > 0 else None

    reporter = Reporter(args, controller, metrics, stop_event, started_wall, deadline_wall)
    exit_reason = "duration reached"

    log(
        f"starting mode={args.mode} commit_mode={args.commit_mode} workers={args.workers} "
        f"rate={'unlimited' if args.rate == 0 else args.rate} duration="
        f"{args.duration or 'until stopped'}s dry_run={args.dry_run}"
    )

    # Fail fast on bad credentials/connectivity before spawning workers.
    try:
        probe = connect(args, action="probe")
        probe.close()
    except Exception as exc:
        metrics.add_error(exc)
        reporter.status = "failed"
        write_json_atomic(STATE_FILE, reporter.state())
        log(f"cannot connect to Oracle: {exc}")
        PID_FILE.unlink(missing_ok=True)
        return 2

    workers = [
        threading.Thread(
            target=run_worker, args=(i, args, controller, metrics, stop_event),
            name=f"ingest-worker-{i + 1}", daemon=True,
        )
        for i in range(args.workers)
    ]
    for w in workers:
        w.start()
    reporter.start()

    try:
        if args.mode == "steady":
            controller.set(active=args.workers, phase="steady")

        elif args.mode == "burst":
            cycle = 0
            controller.set(active=args.workers)
            while not stop_event.is_set():
                cycle += 1
                controller.set(paused=False, phase=f"burst #{cycle}")
                if stop_event.wait(_bounded(args.burst_seconds, deadline)):
                    break
                if deadline and time.monotonic() >= deadline:
                    break
                controller.set(paused=True, phase=f"pause after burst #{cycle}")
                if stop_event.wait(_bounded(args.pause_seconds, deadline)):
                    break
                if deadline and time.monotonic() >= deadline:
                    break

        elif args.mode == "ramp":
            active = min(args.start_workers, args.workers)
            step = 1
            while not stop_event.is_set():
                controller.set(active=active, phase=f"ramp step {step} ({active} workers)")
                step_start = metrics.snapshot()
                if stop_event.wait(_bounded(args.step_seconds, deadline)):
                    break
                rows1, commits1, _, cs1, _ = metrics.snapshot()
                d_commits = commits1 - step_start[1]
                avg_ms = ((cs1 - step_start[3]) / d_commits * 1000) if d_commits else 0.0
                rate = (rows1 - step_start[0]) / args.step_seconds
                log(f"ramp step {step}: {active} workers -> {rate:,.0f} rows/s, avg commit {avg_ms:.2f} ms")
                if args.stop_latency_ms and avg_ms >= args.stop_latency_ms:
                    exit_reason = (f"saturation: avg commit {avg_ms:.1f} ms >= "
                                   f"{args.stop_latency_ms} ms at {active} workers")
                    log(exit_reason)
                    break
                if deadline and time.monotonic() >= deadline:
                    break
                if active >= args.workers:
                    controller.set(phase=f"holding at max ({active} workers)")
                    remaining = (deadline - time.monotonic()) if deadline else None
                    stop_event.wait(remaining)
                    break
                active = min(active + args.step_workers, args.workers)
                step += 1

        if args.mode == "steady":
            stop_event.wait((deadline - time.monotonic()) if deadline else None)

        if stop_requested.is_set():
            exit_reason = "stopped by request"

    finally:
        reporter.status = "stopping"
        controller.set(phase="stopping")
        stop_event.set()
        for w in workers:
            w.join(timeout=30)
        reporter.status = "stopped"
        controller.set(active=0, phase=f"stopped ({exit_reason})")
        reporter.publish(log_line=False)
        rows, commits, errors, _, _ = metrics.snapshot()
        log(f"stopped: {exit_reason}. rows={rows:,} commits={commits:,} errors={errors}")
        PID_FILE.unlink(missing_ok=True)

    return 0


def _bounded(seconds: float, deadline: float | None) -> float:
    if deadline is None:
        return seconds
    return max(0.0, min(seconds, deadline - time.monotonic()))


