def positive_int(value: str) -> int:
    number = int(value)
    if number <= 0:
        raise argparse.ArgumentTypeError("must be greater than zero")
    return number


def non_negative_float(value: str) -> float:
    number = float(value)
    if number < 0:
        raise argparse.ArgumentTypeError("must be zero or greater")
    return number


def add_connection_args(p: argparse.ArgumentParser) -> None:
    p.add_argument("--database", help="PDB/service name (default: ORACLE_DEFAULT_PDB_NAME).")
    p.add_argument("--dry-run", action="store_true", help="Simulate without connecting to Oracle.")
    p.add_argument("--allow-privileged-user", action="store_true",
                   help="Allow running as SYS/SYSTEM (not recommended).")


def add_load_args(p: argparse.ArgumentParser) -> None:
    add_connection_args(p)
    p.add_argument("--mode", choices=["steady", "burst", "ramp"], default="steady")
    p.add_argument("--commit-mode", choices=["row", "batch"], default="row",
                   help="row = commit per message (default), batch = commit per batch.")
    p.add_argument("--workers", type=positive_int, default=4,
                   help="Concurrent sessions; for ramp, the maximum (default: 4).")
    p.add_argument("--rate", type=non_negative_float, default=0,
                   help="Total target rows/sec across workers; 0 = as fast as possible.")
    p.add_argument("--batch-size", type=positive_int, default=200, help="Rows per commit in batch mode.")
    p.add_argument("--payload-bytes", type=positive_int, default=800, help="Approx bytes per row (max 4000).")
    p.add_argument("--duration", type=int, default=600,
                   help="Seconds before auto-stop (default 600). 0 = run until 'stop'.")
    p.add_argument("--report-every", type=positive_int, default=3, help="Seconds between status updates.")
    p.add_argument("--disconnect-when-idle", action="store_true",
                   help="Close sessions during pauses instead of leaving them idle.")
    g = p.add_argument_group("burst mode")
    g.add_argument("--burst-seconds", type=positive_int, default=45)
    g.add_argument("--pause-seconds", type=positive_int, default=60)
    g = p.add_argument_group("ramp mode")
    g.add_argument("--start-workers", type=positive_int, default=1)
    g.add_argument("--step-workers", type=positive_int, default=1)
    g.add_argument("--step-seconds", type=positive_int, default=30)
    g.add_argument("--stop-latency-ms", type=non_negative_float, default=0,
                   help="Auto-stop when average commit latency in a step reaches this. 0 = off.")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Simulate fast message ingest into Oracle (steady / burst / ramp).",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("setup", help=f"Create {TABLE_NAME}.")
    add_connection_args(p)
    p.set_defaults(func=cmd_setup)

    p = sub.add_parser("start", help="Start the load in the background.")
    add_load_args(p)
    p.add_argument("--foreground", action="store_true", help="Run attached to this terminal.")
    p.set_defaults(func=cmd_start)

    p = sub.add_parser("_run", help=argparse.SUPPRESS)
    add_load_args(p)
    p.add_argument("--foreground", action="store_true", help=argparse.SUPPRESS)
    p.set_defaults(func=run_load)

    p = sub.add_parser("status", help="Show current status.")
    p.add_argument("--json", action="store_true")
    p.set_defaults(func=cmd_status)

    p = sub.add_parser("stop", help="Stop the background load.")
    p.add_argument("--timeout", type=positive_int, default=40)
    p.set_defaults(func=cmd_stop)

    p = sub.add_parser("cleanup", help=f"Truncate or drop {TABLE_NAME}.")
    add_connection_args(p)
    p.add_argument("--drop", action="store_true")
    p.add_argument("--yes", action="store_true")
    p.set_defaults(func=cmd_cleanup)

    return parser


def main() -> int:
    args = build_parser().parse_args()
    if getattr(args, "payload_bytes", 0) > 4000:
        sys.exit("--payload-bytes cannot exceed 4000 (VARCHAR2 column limit).")
    return args.func(args)


if __name__ == "__main__":
    raise SystemExit(main())
