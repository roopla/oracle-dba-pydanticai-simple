def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def log(message: str) -> None:
    print(f"[{utc_now()}] {message}", flush=True)


def write_json_atomic(path: Path, data: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_suffix(path.suffix + ".tmp")
    tmp.write_text(json.dumps(data, indent=2, default=str))
    os.replace(tmp, path)


def read_json(path: Path) -> dict[str, Any] | None:
    try:
        return json.loads(path.read_text())
    except (OSError, ValueError):
        return None


def read_pid() -> int | None:
    try:
        return int(PID_FILE.read_text().strip())
    except (OSError, ValueError):
        return None


def _windows_process_alive(pid: int) -> bool:
    """Whether pid is a running process, without signalling it.

    On Windows os.kill(pid, 0) is not a probe: it TERMINATES the process.
    """
    import ctypes

    process_query_limited_information = 0x1000
    still_active = 259
    kernel32 = ctypes.windll.kernel32
    handle = kernel32.OpenProcess(process_query_limited_information, False, pid)
    if not handle:
        return False
    try:
        code = ctypes.c_ulong()
        if not kernel32.GetExitCodeProcess(handle, ctypes.byref(code)):
            return False
        return code.value == still_active
    finally:
        kernel32.CloseHandle(handle)


def is_our_process(pid: int) -> bool:
    """True if pid is alive and is this simulator (guards against PID reuse)."""
    if os.name == "nt":
        # No command line to check here: trust a live PID, as on macOS.
        return _windows_process_alive(pid)
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        return False
    cmdline = Path(f"/proc/{pid}/cmdline")
    if cmdline.exists():
        try:
            text = cmdline.read_bytes().replace(b"\0", b" ").decode(errors="ignore")
        except OSError:
            return True
        return "ingest_simulator" in text and (" _run" in text or " start" in text)
    return True  # No /proc (macOS): trust the live PID.


def running_pid() -> int | None:
    pid = read_pid()
    if pid is not None and is_our_process(pid):
        return pid
    return None


def tail(path: Path, lines: int = 15) -> str:
    try:
        return "\n".join(path.read_text(errors="ignore").splitlines()[-lines:])
    except OSError:
        return "(no log output)"


