@dataclass
class Metrics:
    lock: threading.Lock = field(default_factory=threading.Lock)
    rows: int = 0
    commits: int = 0
    errors: int = 0
    commit_seconds: float = 0.0
    last_error: str | None = None

    def add(self, rows: int, commit_seconds: float) -> None:
        with self.lock:
            self.rows += rows
            self.commits += 1
            self.commit_seconds += commit_seconds

    def add_error(self, exc: BaseException) -> None:
        with self.lock:
            self.errors += 1
            self.last_error = f"{type(exc).__name__}: {str(exc)[:300]}"

    def snapshot(self) -> tuple[int, int, int, float, str | None]:
        with self.lock:
            return self.rows, self.commits, self.errors, self.commit_seconds, self.last_error


class Controller:
    """Decides which workers are active, based on the load mode."""

    def __init__(self, max_workers: int) -> None:
        self.max_workers = max_workers
        self.active_workers = 0
        self.paused = False
        self.phase = "starting"
        self._cond = threading.Condition()

    def set(self, *, active: int | None = None, paused: bool | None = None, phase: str | None = None) -> None:
        with self._cond:
            if active is not None:
                self.active_workers = max(0, min(active, self.max_workers))
            if paused is not None:
                self.paused = paused
            if phase is not None:
                self.phase = phase
            self._cond.notify_all()

    def is_active(self, worker_index: int) -> bool:
        return not self.paused and worker_index < self.active_workers

    def wait_for_change(self, timeout: float) -> None:
        with self._cond:
            self._cond.wait(timeout)

    def effective_active(self) -> int:
        return 0 if self.paused else self.active_workers


# ---------------------------------------------------------------------------
# Worker: one Oracle session each, like one consumer instance
# ---------------------------------------------------------------------------


def make_row(worker_id: int, payload_bytes: int) -> tuple[Any, ...]:
    message_id = str(uuid.uuid4())
    customer = random.choice(CUSTOMERS)
    product = random.choice(PRODUCTS)
    quantity = random.randint(1, 20)
    price = round(random.uniform(5, 500), 2)
    status = random.choice(STATUSES)
    body = json.dumps(
        {"message_id": message_id, "customer_name": customer, "product_name": product,
         "quantity": quantity, "unit_price": price, "order_status": status}
    )
    pad = max(0, payload_bytes - len(body))
    payload = body + "".join(random.choices(string.ascii_letters, k=pad))
    return (message_id, customer, product, quantity, price, status, worker_id, payload[:4000])


def run_worker(
    index: int,
    args: argparse.Namespace,
    controller: Controller,
    metrics: Metrics,
    stop_event: threading.Event,
) -> None:
    worker_id = index + 1
    connection = None
    cursor = None
    consecutive_errors = 0
    next_due = time.monotonic()

    try:
        while not stop_event.is_set():
            if not controller.is_active(index):
                if connection is not None and args.disconnect_when_idle:
                    connection.close()
                    connection = cursor = None
                controller.wait_for_change(0.5)
                next_due = time.monotonic()
                continue

            try:
                if connection is None:
                    connection = connect(args, action=f"{args.mode}:{args.commit_mode}")
                    cursor = connection.cursor()

                if args.commit_mode == "row":
                    cursor.execute(INSERT_SQL, make_row(worker_id, args.payload_bytes))
                    rows = 1
                else:
                    batch = [make_row(worker_id, args.payload_bytes) for _ in range(args.batch_size)]
                    cursor.executemany(INSERT_SQL, batch)
                    rows = len(batch)

                t0 = time.perf_counter()
                connection.commit()
                metrics.add(rows, time.perf_counter() - t0)
                consecutive_errors = 0

            except Exception as exc:  # keep running through transient Oracle errors
                metrics.add_error(exc)
                consecutive_errors += 1
                log(f"worker {worker_id}: {type(exc).__name__}: {str(exc)[:200]}")
                try:
                    if connection is not None:
                        connection.rollback()
                except Exception:
                    try:
                        connection.close()
                    except Exception:
                        pass
                    connection = cursor = None
                if consecutive_errors >= MAX_CONSECUTIVE_ERRORS:
                    log(f"worker {worker_id}: {consecutive_errors} consecutive errors, giving up")
                    return
                stop_event.wait(min(2 ** min(consecutive_errors, 4) * 0.25, 5.0))
                continue

            # Optional global rate cap, shared evenly across active workers.
            if args.rate > 0:
                active = max(controller.effective_active(), 1)
                per_worker = args.rate / active
                next_due += rows / per_worker
                delay = next_due - time.monotonic()
                if delay > 0:
                    stop_event.wait(delay)
                elif delay < -1.0:
                    next_due = time.monotonic()  # fell behind; don't try to catch up
    finally:
        if connection is not None:
            try:
                connection.rollback()
                connection.close()
            except Exception:
                pass


# ---------------------------------------------------------------------------
# Reporter: progress log + state file for `status`
# ---------------------------------------------------------------------------


class Reporter(threading.Thread):
    def __init__(self, args, controller, metrics, stop_event, started_wall, deadline_wall):
        super().__init__(name="ingest-sim-reporter", daemon=True)
        self.args = args
        self.controller = controller
        self.metrics = metrics
        self.stop_event = stop_event
        self.started_wall = started_wall
        self.deadline_wall = deadline_wall
        self.last = (time.monotonic(), 0, 0, 0.0)
        self.interval_rate = 0.0
        self.interval_commit_rate = 0.0
        self.interval_commit_ms = 0.0
        self.status = "running"

    def sample(self) -> None:
        now = time.monotonic()
        rows, commits, _, commit_s, _ = self.metrics.snapshot()
        t_prev, r_prev, c_prev, cs_prev = self.last
        dt = max(now - t_prev, 1e-3)
        dc = commits - c_prev
        self.interval_rate = (rows - r_prev) / dt
        self.interval_commit_rate = dc / dt
        self.interval_commit_ms = ((commit_s - cs_prev) / dc * 1000) if dc else 0.0
        self.last = (now, rows, commits, commit_s)

    def state(self) -> dict[str, Any]:
        rows, commits, errors, commit_s, last_error = self.metrics.snapshot()
        elapsed = max(time.time() - self.started_wall, 1e-3)
        return {
            "status": self.status,
            "pid": os.getpid(),
            "mode": self.args.mode,
            "commit_mode": self.args.commit_mode,
            "phase": self.controller.phase,
            "active_workers": self.controller.effective_active(),
            "max_workers": self.args.workers,
            "rows_per_sec": round(self.interval_rate, 1),
            "commits_per_sec": round(self.interval_commit_rate, 1),
            "avg_commit_ms": round(self.interval_commit_ms, 2),
            "rows_total": rows,
            "commits_total": commits,
            "errors_total": errors,
            "avg_rows_per_sec_overall": round(rows / elapsed, 1),
            "last_error": last_error,
            "started_at": datetime.fromtimestamp(self.started_wall, timezone.utc).isoformat(timespec="seconds"),
            "ends_at": (
                datetime.fromtimestamp(self.deadline_wall, timezone.utc).isoformat(timespec="seconds")
                if self.deadline_wall else "when stopped"
            ),
            "updated_at": utc_now(),
            "dry_run": self.args.dry_run,
            "config": {
                k: getattr(self.args, k)
                for k in ("database", "workers", "rate", "batch_size", "payload_bytes", "duration",
                          "burst_seconds", "pause_seconds", "start_workers", "step_workers",
                          "step_seconds", "stop_latency_ms")
            },
        }

    def publish(self, log_line: bool = True) -> None:
        self.sample()
        write_json_atomic(STATE_FILE, self.state())
        if log_line:
            rows, commits, errors, _, _ = self.metrics.snapshot()
            log(
                f"phase={self.controller.phase} active={self.controller.effective_active()}/"
                f"{self.args.workers} rows/s={self.interval_rate:,.0f} commits/s="
                f"{self.interval_commit_rate:,.0f} commit_ms={self.interval_commit_ms:.2f} "
                f"rows={rows:,} errors={errors}"
            )

    def run(self) -> None:
        while not self.stop_event.wait(self.args.report_every):
            self.publish()


